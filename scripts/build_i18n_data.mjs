#!/usr/bin/env node
/**
 * build_i18n_data.mjs — writes data.en.js / data.hi.js for the SPA homes (/en/, /hi/).
 * Same shape as data.js (`export const rawData`), with translations from i18n/<lang>.json
 * overlaid; anything without a current translation stays Italian.
 * /en/index.html and /hi/index.html remap "/data.js" to these files via an import map.
 */
import fs from 'node:fs';
import path from 'node:path';
import { rawData } from '../data.js';
import { ROOT, TARGET_LANGS, loadTranslations, localizeIssue, buildRefContext } from './i18n_lib.mjs';

for (const lang of TARGET_LANGS) {
  const tr = loadTranslations(lang);
  const ctx = buildRefContext(rawData, tr);
  const counts = { full: 0, partial: 0, none: 0 };
  const strip = (r) => { const { _src, _lang, ...x } = r; return x; };
  const out = rawData.map((ch, idx) => {
    const { issue, status } = localizeIssue(ch, idx, tr, undefined, ctx);
    counts[status]++;
    const { _id, ...rest } = issue;
    return { ...rest, _i18n: status, subchapters: rest.subchapters.map(({ _titleLang, ...s }) => ({ ...s, references: (s.references || []).map(strip), connections: (s.connections || []).map(strip) })) };
  });
  const body = `// AUTO-GENERATED by scripts/build_i18n_data.mjs — do not edit. Source: data.js + i18n/${lang}.json\nexport const rawData = ${JSON.stringify(out)};\n`;
  fs.writeFileSync(path.join(ROOT, `data.${lang}.js`), body, 'utf-8');
  console.log(`✅ data.${lang}.js — ${out.length} entries`, counts);
}
